#!/usr/bin/env node
// Donor wall heroes (2026-10-25): each donor card on donate.html is greeted by
// a hero who says that hero's own in-game "thank you" line.
//
// The lines are never typed by hand. They are Valve's hero chat wheel
// "_thank" messages, read from the game's localization files (mirrored by
// dotabuff/d2vpkr), and the hero names are Valve's official ones from
// dota2.com/datafeed. This script writes assets/donor-heroes.js; edit the
// HEROES list below to change who appears, then re-run.
//
//   node scripts/donor-heroes.mjs           regenerate assets/donor-heroes.js
//
// Hero art is the mirror the mobile BP page already uses:
// cdn.amefys.com/hero-art/v2/portraits/<hero>.webp (256×144). Every hero is
// checked there before the file is written, so the page never asks for a
// picture that is not on the CDN.
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'assets/donor-heroes.js')
const LOC = 'https://raw.githubusercontent.com/dotabuff/d2vpkr/master/dota/resource/localization'
const HEROLIST = 'https://www.dota2.com/datafeed/herolist?language=schinese'
const ART = 'https://cdn.amefys.com/hero-art/v2/portraits'

// Popular heroes whose thank-you line reads as a thank-you on a donor wall.
// Order does not matter: the page picks one per donor from a stable seed.
const HEROES = [
  'axe', 'pudge', 'crystal_maiden', 'sven', 'invoker', 'juggernaut', 'brewmaster',
  'centaur', 'spectre', 'keeper_of_the_light', 'kunkka', 'slark', 'legion_commander',
  'luna', 'mirana', 'witch_doctor', 'storm_spirit', 'earthshaker', 'tinker', 'arc_warden',
  'muerta', 'ringmaster', 'snapfire', 'bane', 'jakiro', 'tusk', 'techies', 'zuus'
]

async function text(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`)
  return (await res.text()).replace(/^﻿/, '')
}

function thankLines(file) {
  const out = {}
  for (const [, key, msg] of file.matchAll(/"dota_chatwheel_message_([a-z0-9_]+)_thank"\s+"([^"]*)"/g)) out[key] = msg
  return out
}

const [zhFile, enFile, list] = await Promise.all([
  text(`${LOC}/hero_chat_wheel_schinese.txt`),
  text(`${LOC}/hero_chat_wheel_english.txt`),
  text(HEROLIST).then((t) => JSON.parse(t).result.data.heroes)
])
const zh = thankLines(zhFile)
const en = thankLines(enFile)
const names = new Map(list.map((h) => [h.name.replace('npc_dota_hero_', ''), h]))

const heroes = []
for (const id of HEROES) {
  const h = names.get(id)
  if (!h) throw new Error(`${id}: not in the official hero list`)
  if (!zh[id] || !en[id]) throw new Error(`${id}: no chat wheel thank line`)
  const art = await fetch(`${ART}/${id}.webp`, { method: 'HEAD' })
  if (!art.ok) throw new Error(`${id}: ${ART}/${id}.webp → HTTP ${art.status}`)
  heroes.push({ id, name: { zh: h.name_loc, en: h.name_english_loc }, line: { zh: zh[id], en: en[id] } })
}

const body = `// Generated by scripts/donor-heroes.mjs — do not edit by hand.
// Lines: Valve's hero chat wheel "thank" messages (game localization files).
// Names: dota2.com/datafeed/herolist. Hero names, art and lines © Valve.
window.AMEFYS_DONOR_HEROES = ${JSON.stringify(heroes, null, 1).replace(/\n\s*/g, ' ')}
`
writeFileSync(OUT, body)
console.log(`wrote ${heroes.length} heroes → ${OUT}`)
